/**
 * Bulk-import products/services from a CSV file into data/products.json
 *
 * Usage:
 *   node tools/import-products.js data/products_upload.csv
 *
 * CSV columns (header row required):
 *   category_id,category_title,product_id,name,price,price_min,price_max,sizes,description,image_url,stock
 *
 * Pricing (one of these is required per row):
 *   - fixed price: set `price` (e.g. 12000)
 *   - quote range: leave `price` empty, set `price_min` + `price_max`
 *     (bot enters QUOTE MODE: collects details, admin sends exact quote)
 *
 * Rules:
 * - sizes separated by |  e.g.  S|M|L|XL (optional, can be empty)
 * - avoid commas inside fields
 * - image_url can be empty — bot sends text-only details until photos are ready
 * - stock can be empty (= always available, ideal for services)
 */
import fs from "node:fs";
import path from "node:path";

const input = process.argv[2] || "data/products_upload.csv";
const out = path.join("data", "products.json");

const lines = fs.readFileSync(input, "utf8").trim().split(/\r?\n/);
if (lines.length < 2) {
  console.error("❌ CSV has no data rows.");
  process.exit(1);
}
const header = lines[0].split(",").map((h) => h.trim());
const idx = (n) => header.indexOf(n);
for (const col of ["category_id", "product_id", "name"]) {
  if (idx(col) === -1) {
    console.error(`❌ Missing required column: ${col}`);
    process.exit(1);
  }
}
const col = (c, n) => (idx(n) === -1 ? "" : (c[idx(n)] || "").trim());

const cats = new Map();
const products = [];
const seen = new Set();
let fixed = 0;
let ranged = 0;
for (const line of lines.slice(1)) {
  if (!line.trim()) continue;
  const c = line.split(",").map((s) => s.trim());
  const catId = col(c, "category_id");
  const catTitle = col(c, "category_title") || catId;
  const prodId = col(c, "product_id");
  const name = col(c, "name");
  if (!catId || !prodId || !name) {
    console.warn("⚠️  Skipping incomplete row:", line.slice(0, 80));
    continue;
  }
  if (seen.has(prodId.toLowerCase())) {
    console.warn(`⚠️  Duplicate product_id ${prodId} — skipping`);
    continue;
  }
  const priceRaw = col(c, "price");
  const minRaw = col(c, "price_min");
  const maxRaw = col(c, "price_max");
  const hasFixed = priceRaw !== "" && Number(priceRaw) > 0;
  const hasRange = minRaw !== "" && maxRaw !== "" && Number(minRaw) > 0 && Number(maxRaw) > 0;
  if (!hasFixed && !hasRange) {
    console.warn(`⚠️  No valid pricing for ${prodId} — skipping (need price OR price_min+price_max)`);
    continue;
  }
  seen.add(prodId.toLowerCase());
  if (hasFixed) fixed++;
  else ranged++;
  if (!cats.has(catId)) cats.set(catId, { id: catId, title: catTitle });
  const sizesRaw = col(c, "sizes");
  const stockRaw = col(c, "stock");
  products.push({
    id: prodId,
    cat: catId,
    name,
    price: hasFixed ? Number(priceRaw) : 0,
    ...(hasRange ? { priceMin: Number(minRaw), priceMax: Number(maxRaw) } : {}),
    sizes: sizesRaw ? sizesRaw.split("|").map((s) => s.trim()).filter(Boolean) : [],
    desc: col(c, "description"),
    image: col(c, "image_url"),
    stock: stockRaw === "" ? null : Number(stockRaw),
  });
}

const data = {
  _note: "Generated by tools/import-products.js — edit the CSV and re-run to update.",
  categories: [...cats.values()],
  products,
};
fs.writeFileSync(out, JSON.stringify(data, null, 2));
console.log(`✅ Imported ${products.length} items in ${cats.size} categories → ${out}`);
console.log(`   Fixed-price: ${fixed} · Quote-range: ${ranged}`);
